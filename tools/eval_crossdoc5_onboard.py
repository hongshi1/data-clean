"""Crossdoc x5 evaluation with per-document onboarded configs.

For each doc's 30 instances, switch the default lexicon+rulepack to that
doc's onboard config (generated by onboard_new_document), then run the
full. Compares: (a) 04号通用配置 (b) 每文档onboard配置.
"""
from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

from algorithms.consistency.eval_lib import (
    build_qa_input,
    classification_metrics,
    load_label_rows,
)
from algorithms.consistency.ner_lexicon import load_lexicon, set_default_lexicon
from algorithms.consistency.rulepack import load_rulepack, set_default_rulepack
from algorithms.consistency.verifier import CascadeVerifier

SET = "data/gjb_438c/qa_frozen/crossdoc5_evalset_v1.jsonl"
LEX = "config/ner_lexicons/{doc}_scene.json"
PACK = "config/rulepacks/{doc}_onboard_v1.json"
SILVER_FALLBACK = ("data/gjb_438c/runs/"
                   "review_qa_with_glm53_582b51e5_20261021_145212"
                   "/final_labels.jsonl")


def doc_of(instance_id: str) -> str:
    # C05QA-xx -> 05 ; C06QA-xx -> 06 ...
    return instance_id[1:3]


def group_records() -> dict[str, list[dict]]:
    groups: dict[str, list[dict]] = defaultdict(list)
    for line in open(SET, encoding="utf-8"):
        rec = json.loads(line)
        groups[doc_of(rec["instance_id"])].append(rec)
    return groups


def run_group(records: list[dict], verifier: CascadeVerifier,
              labels: dict[str, str]) -> tuple[list[str], list[str]]:
    y_true: list[str] = []
    y_pred: list[str] = []
    for rec in records:
        label = rec.get("sound_label") or labels.get(rec["instance_id"], "")
        if not label:
            continue
        result = verifier.verify_record(rec)
        y_true.append(label)
        y_pred.append(result.verdict)
    return y_true, y_pred


def main() -> None:
    labels = load_label_rows(Path(SILVER_FALLBACK))
    groups = group_records()
    print(f"groups: {sorted(g for g in groups)}")

    results: dict[str, dict[str, dict]] = {}

    # (a) 通用04号配置
    generic = CascadeVerifier(preset="full", scene="srs_scene1")
    per_doc: dict[str, dict] = {}
    all_true: list[str] = []
    all_pred: list[str] = []
    for doc, records in sorted(groups.items()):
        y_true, y_pred = run_group(records, generic, labels)
        m = classification_metrics(y_true, y_pred)
        per_doc[doc] = m
        all_true.extend(y_true)
        all_pred.extend(y_pred)
    total = classification_metrics(all_true, all_pred)
    results["generic04"] = {"per_doc": per_doc, "total": total}
    print(f"[generic04] total macroF1={total['macro_f1']:.4f}")

    # (b) 每文档onboard配置(构造一次引擎, 逐文档切默认配置)
    verifier = CascadeVerifier(preset="full", scene="srs_scene1")
    per_doc_on: dict[str, dict] = {}
    all_true = []
    all_pred = []
    for doc, records in sorted(groups.items()):
        if doc == "04":
            set_default_lexicon(load_lexicon(
                "config/ner_lexicons/srs_scene1.json"))
            set_default_rulepack(load_rulepack(
                "config/rulepacks/srs_gjb_v1.json"))
        else:
            pack_name = ("doc06_v1" if doc == "06"
                         else f"doc{doc}_onboard_v1")
            lex_path = LEX.format(doc=f"doc{doc}")
            pack_path = f"config/rulepacks/{pack_name}.json"
            set_default_lexicon(load_lexicon(lex_path))
            set_default_rulepack(load_rulepack(pack_path))
        y_true, y_pred = run_group(records, verifier, labels)
        m = classification_metrics(y_true, y_pred)
        per_doc_on[doc] = m
        all_true.extend(y_true)
        all_pred.extend(y_pred)
        print(f"  [onboard doc{doc}] macroF1={m['macro_f1']:.4f}")
    total_on = classification_metrics(all_true, all_pred)
    results["onboard"] = {"per_doc": per_doc_on, "total": total_on}
    print(f"[onboard] total macroF1={total_on['macro_f1']:.4f}")

    out = "docs/srs_project/paper/crossdoc_onboard_result.json"
    with open(out, "w", encoding="utf-8") as f:
        json.dump({
            "generic04_total": total,
            "onboard_total": total_on,
            "per_doc": {d: {
                "generic": per_doc[d]["macro_f1"],
                "onboard": per_doc_on[d]["macro_f1"],
            } for d in sorted(groups)},
        }, f, ensure_ascii=False, indent=1)
    print("saved:", out)


if __name__ == "__main__":
    main()
