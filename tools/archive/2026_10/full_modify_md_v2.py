def make_table(rows):
    """rows: list of list[str]; 生成 MinerU 风格 HTML 表格"""
    trs = []
    for row in rows:
        tds = "".join(f"<td><p>{c}</p></td>" for c in row)
        trs.append(f"<tr>{tds}</tr>")
    return "<table>" + "".join(trs) + "</table>"


