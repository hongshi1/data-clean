def replace_table(text, header_marker, new_table):
    """将 header_marker 之后第一个 <table>...</table> 替换为 new_table"""
    i = text.find(header_marker)
    if i < 0:
        print(f"  ⚠ 未找到 {header_marker[:30]}")
        return text
    j = text.find("<table>", i)
    if j < 0:
        print(f"  ⚠ {header_marker[:30]} 后无表格")
        return text
    k = text.find("</table>", j) + len("</table>")
    return text[:j] + new_table + text[k:]


